#!/usr/bin/env node
// Writes docs/ASSETS.md: every file under assets/ and fonts/ with dimensions, size, format,
// the pages that reference it, and its role. Run after adding or replacing an asset:
//   node scripts/assets-inventory.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
let sharp = null; try { sharp = (await import('sharp')).default; } catch {}

const pages = [];
const walk = d => { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) { if (!['dist', 'node_modules', '.git', 'docs'].includes(e.name)) walk(p); } else if (e.name.endsWith('.html') || e.name.endsWith('.mjs') || e.name.endsWith('.css')) pages.push(p); } };
walk(ROOT);
const texts = pages.map(p => [path.relative(ROOT, p), fs.readFileSync(p, 'utf8')]);

const ROLES = {
  'assets/hero-core.png': 'Homepage hero: the machine core render. Default og:image fallback until brand/og-default.png.',
  'assets/engine.png': 'Homepage engine-room card: Helmsman engine render.',
  'assets/harness.png': 'Homepage engine-room card: harness render.',
  'assets/dashboard.png': 'Homepage engine-room card: command dashboard console.',
  'assets/training-hall.png': 'Homepage training-centre band: the assembly floor.',
  'assets/silock-lock.png': 'Homepage S◉LOCK band.',
  'assets/scrollrail.js': 'House scroll rail (blue dot on the right edge). Loaded deferred on every page.',
  'assets/house.js': 'House script: consent notice, reveal-on-scroll, flyout menus, cookie reset. Loaded deferred on every page.',
  'assets/home.js': 'Homepage script: hero image class, sibling stagger, ratings coverflow.',
  'assets/rotate-hint.js': 'Homepage: one-time landscape hint on small portrait touch screens.',
  'fonts/hanken.woff2': 'Hanken Grotesk variable (100 to 900). The only text face. Preloaded on every page.',
  'fonts/instrument-italic.woff2': 'Instrument Serif italic. The <em class="i"> accent face.',
};
const roleFor = f => {
  if (ROLES[f]) return ROLES[f];
  if (/^assets\/pipe\/p\d\d\.(webp|png)$/.test(f)) return 'Product hero render (896x1152 webp on tiles and product heroes; png is the og:image).';
  if (/^assets\/pipe\/p\d\d-flow\.png$/.test(f)) return 'Product page: the signature full-width flow band (2304x1792).';
  if (/^assets\/pipe\/p\d\d-mech\.png$/.test(f)) return 'Product page: the mechanics render beside the layer list.';
  if (f.startsWith('assets/brand/')) return 'Brand kit (see docs/BRAND.md). Generated by scripts/brand-kit.mjs; do not hand-edit.';
  if (f.startsWith('fonts/')) return 'Not referenced by any page. Candidate for removal from the served tree.';
  return '';
};

const rows = [];
const scan = async (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { await scan(p); continue; }
    const f = path.relative(ROOT, p).split(path.sep).join('/');
    const st = fs.statSync(p);
    let dims = '';
    if (sharp && /\.(png|jpe?g|webp|avif|svg)$/i.test(f)) { try { const m = await sharp(p).metadata(); dims = `${m.width}×${m.height}`; } catch {} }
    const users = texts.filter(([n, t]) => t.includes(path.basename(f))).map(([n]) => n);
    rows.push({ f, size: st.size, dims, users: users.length, role: roleFor(f) });
  }
};
await scan(path.join(ROOT, 'assets'));
await scan(path.join(ROOT, 'fonts'));

const kb = n => n >= 1048576 ? (n / 1048576).toFixed(1) + ' MB' : Math.round(n / 1024) + ' KB';
let md = `# Asset pack\n\nGenerated by \`node scripts/assets-inventory.mjs\` on ${new Date().toISOString().slice(0, 10)}. Every file the site ships, where it is used and what it is for. Rules for adding assets are at the end; the logo kit and brand rules are in [BRAND.md](./BRAND.md).\n\n`;
md += `| File | Format | Dimensions | Size | Used by | Role |\n|---|---|---|---|---|---|\n`;
for (const r of rows) md += `| \`${r.f}\` | ${path.extname(r.f).slice(1)} | ${r.dims} | ${kb(r.size)} | ${r.users} file${r.users === 1 ? '' : 's'} | ${r.role} |\n`;
md += `\n## Rules\n\n- Source of truth is \`assets/\` at the repo root; \`dist/assets/\` is written by \`node build.mjs\`, which also emits AVIF and WebP variants and wraps every png/jpg in a \`<picture>\` element. Never hand-edit \`dist/\`.\n- Product renders follow the pipe naming: \`pNN.webp\` (hero, 896×1152), \`pNN.png\` (og:image), \`pNN-flow.png\` (flow band, 2304×1792), \`pNN-mech.png\` (mechanics render). A new product needs all four.\n- Every content image in a page carries descriptive alt text with the product name, explicit width and height, and \`loading="lazy"\` below the fold. Decorative images carry \`alt=""\`.\n- Photography is not used. Renders are white-studio, single blue accent, matching the house look (paper, ink, core blue).\n- Fonts: only \`hanken.woff2\` and \`instrument-italic.woff2\` ship; the build removes anything else from \`dist/fonts/\`.\n- Logos, icons, social images and favicons come from the brand kit in \`assets/brand/\` and are regenerated with \`node scripts/brand-kit.mjs\`; never draw a new version of the mark by hand.\n`;
fs.writeFileSync(path.join(ROOT, 'docs', 'ASSETS.md'), md);
console.log(`docs/ASSETS.md: ${rows.length} assets`);
